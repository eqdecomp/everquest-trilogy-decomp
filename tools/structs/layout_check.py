r"""Ask VC6 for the real sizeof / offsetof / alignment of a header's structs and compare.

    ..\.venv\Scripts\python.exe structs\layout_check.py --repo TREE --header include/trilogy/character.h
        [--struct NAME] [--out DIR] [--scratch DIR] [--cpp] [--flags "/Zp4"] [--vc6 DIR]

How: the header's struct definitions are read with cparse (the names and members, not their sizes). A small C
file is generated in the scratch dir (default <workspace>\build\structs\scratch\layout, refused if
inside --repo):

    #define C_ASSERT(e)                  (so a wrong assert in the header cannot stop the build)
    #include "trilogy/character.h"
    unsigned int eqd_layout[] = { sizeof(S), alignment-probe(S), offsetof(S, m), ... };

and compiled with the repo's include path using VC6's CL.EXE (`/c /FAs`; the toolchain comes from paths.local.ini
[toolchain] vc6 via eqd_unicorn.vc6, or --vc6 / EQD_TOOLCHAIN_VC6). Nothing is linked or run: the values are
read from the assembler listing, where the initialised array appears as `DD` constants. The alignment probe is
offsetof(struct { char c; S t; }, t) (VC6 has no __alignof).

Reported (DIR/layout_check.md + layout_check.json, default DIR = scratch):
  * compiled sizeof/alignment and every member offset per struct
  * C_ASSERT(sizeof(..)==N) / C_ASSERT(offsetof(..)==N) found in the header: OK or MISMATCH vs the compiler
  * the parser's own layout (the one unify_diff.py / census.py use): MISMATCH list vs the compiler, so the
    portable layout code is itself checked against VC6
Exit status 0 when the compile succeeded and nothing mismatches, 1 otherwise.
Bitfield members and members of unknown type (parser could not size them) are listed but not offset-probed
where C forbids it.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
for _p in (HERE.parent / "unicorn",):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))
import cparse as C  # noqa: E402

def _workspace() -> Path:
    """EQD_ROOT, or the first parent of this checkout holding paths.local.ini, else the checkout's parent."""
    env = os.environ.get("EQD_ROOT")
    if env:
        return Path(env)
    for d in HERE.parents:
        if (d / "paths.local.ini").is_file():
            return d
    return HERE.parents[1]


DEFAULT_SCRATCH = _workspace() / "build" / "structs" / "scratch" / "layout"
ASSERT_SIZE = re.compile(r"C_ASSERT\s*\(\s*sizeof\s*\(\s*([A-Za-z_][\w\s]*?)\s*\)\s*==\s*([^;]+?)\s*\)\s*;?\s*$", re.M)
ASSERT_OFF = re.compile(r"C_ASSERT\s*\(\s*offsetof\s*\(\s*([A-Za-z_][\w\s]*?)\s*,\s*([\w.\[\]]+)\s*\)\s*==\s*([^;]+?)\s*\)\s*;?\s*$", re.M)


def find_vc6(arg: str | None) -> Path:
    if arg:
        return Path(arg)
    try:
        from eqd_unicorn import vc6
        return vc6.toolchain_dir("vc6")
    except Exception as ex:               # noqa: BLE001
        raise SystemExit(f"cannot find VC6 ({ex}); pass --vc6 DIR or set EQD_TOOLCHAIN_VC6")


def vc6_env(vc6: Path) -> dict:
    from eqd_unicorn import vc6 as V
    return V.vc6_env(vc6)


def struct_ref(d: C.StructDef) -> str:
    """How C code names the type: typedef alias, else `struct Tag`."""
    if d.aliases:
        return d.aliases[0]
    return f"{d.kw} {d.tag}"


def pick_structs(idx: C.Index, rel: str, only: str | None):
    out = []
    fi = idx.files[rel]
    for d in fi.structs:
        if d.parent is not None:
            continue
        if not (d.tag or d.aliases):
            continue
        if only and only not in d.names:
            continue
        out.append(d)
    return out


def probe_list(idx: C.Index, structs):
    """-> (entries [(struct_ref, kind, path)], skipped notes)"""
    entries, notes = [], []
    for d in structs:
        ref = struct_ref(d)
        lay = idx.layout(d)
        entries.append((ref, "size", ""))
        entries.append((ref, "align", ""))
        seen = set()
        for m in lay.members:
            if m.bits is not None:
                notes.append(f"{ref}.{m.path}: bitfield, offset not probed")
                continue
            if m.path in seen or m.path == "__vptr":
                continue
            seen.add(m.path)
            entries.append((ref, "off", m.path))
    return entries, notes


def gen_c(include_arg: str, entries) -> str:
    L = ["/* generated by layout_check.py */", "#include <stddef.h>", "#define C_ASSERT(e)",
         f'#include "{include_arg}"', ""]
    probes = {}
    for ref, kind, path in entries:
        if kind == "align" and ref not in probes:
            probes[ref] = f"eqd_al{len(probes)}"
            L.append(f"struct {probes[ref]} {{ char c; {ref} t; }};")
    L += ["", "unsigned int eqd_layout[] = {"]
    for ref, kind, path in entries:
        if kind == "size":
            L.append(f"    sizeof({ref}),")
        elif kind == "align":
            L.append(f"    offsetof(struct {probes[ref]}, t),")
        else:
            L.append(f"    offsetof({ref}, {path}),")
    L.append("    0xFFFFFFFFu")
    L.append("};")
    return "\n".join(L) + "\n"


def parse_listing(text: str):
    m = re.search(r"^(?:_|\?)eqd_layout\S*\s+DD\s+(\S+)(.*?)^_DATA\s+ENDS", text, re.S | re.M)
    if not m:
        return None
    vals = [m.group(1)] + re.findall(r"^\s+DD\s+([0-9A-Za-z]+)", m.group(2), re.M)
    out = []
    for v in vals:
        out.append(int(v[:-1], 16) if v.upper().endswith("H") else int(v, 0))
    return out


def run_cl(vc6: Path, env, scratch: Path, src: Path, include_dirs, flags, cpp: bool):
    cmd = [str(vc6 / "Bin" / "CL.EXE"), "/nologo", "/c", "/W3", "/FAs", f"/Fa{scratch}\\", f"/Fo{scratch}\\"]
    cmd += list(flags) + [f"/I{d}" for d in include_dirs]
    cmd.append("/TP" if cpp else "/TC")
    cmd.append(str(src))
    p = subprocess.run(cmd, env=env, cwd=scratch, capture_output=True, text=True, errors="replace")
    return p.returncode, p.stdout + p.stderr


def hexs(v):
    return f"0x{v:X}"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo", required=True)
    ap.add_argument("--header", required=True, help="path relative to --repo, e.g. include/trilogy/character.h")
    ap.add_argument("--struct", help="only this struct (typedef or tag name)")
    ap.add_argument("--out", help="report folder (default: the scratch folder)")
    ap.add_argument("--scratch", default=str(DEFAULT_SCRATCH))
    ap.add_argument("--cpp", action="store_true", help="compile as C++ (default: C, then C++ if C fails)")
    ap.add_argument("--flags", default="", help="extra CL options, e.g. '/Zp4'")
    ap.add_argument("--vc6")
    a = ap.parse_args(argv)

    repo = Path(a.repo).resolve()
    scratch = Path(a.scratch).resolve()
    try:
        scratch.relative_to(repo)
        raise SystemExit(f"scratch {scratch} is inside the source tree {repo}; refusing")
    except ValueError:
        pass
    hdr = (repo / a.header).resolve()
    if not hdr.is_file():
        raise SystemExit(f"no such header: {hdr}")
    rel = hdr.relative_to(repo).as_posix()
    scratch.mkdir(parents=True, exist_ok=True)
    stem = re.sub(r"\W", "_", Path(a.header).stem) + (f"_{a.struct}" if a.struct else "")

    idx = C.load_index(repo, ("include",))
    if rel not in idx.files:
        idx.add(C.parse_file(rel, hdr.read_text(encoding="utf-8", errors="replace")))
        idx.resolve_aliases()
    structs = pick_structs(idx, rel, a.struct)
    if not structs:
        raise SystemExit("no struct definitions found in the header" + (f" named {a.struct}" if a.struct else ""))
    entries, notes = probe_list(idx, structs)

    inc_root = repo / "include"
    try:
        inc_arg = hdr.relative_to(inc_root).as_posix()
        incs = [inc_root]
    except ValueError:
        inc_arg = hdr.as_posix()
        incs = [hdr.parent, inc_root]
    src = scratch / f"{stem}_probe.c"
    src.write_text(gen_c(inc_arg, entries), encoding="utf-8")

    vc6 = find_vc6(a.vc6)
    env = vc6_env(vc6)
    flags = a.flags.split()
    rc, log = run_cl(vc6, env, scratch, src, incs, flags, a.cpp)
    used_cpp = a.cpp
    if rc != 0 and not a.cpp:
        rc2, log2 = run_cl(vc6, env, scratch, src, incs, flags, True)
        log = "--- as C ---\n" + log + "\n--- as C++ ---\n" + log2
        if rc2 == 0:
            rc, used_cpp = rc2, True
    asm = scratch / f"{stem}_probe.asm"
    vals = parse_listing(asm.read_text(errors="replace")) if rc == 0 and asm.is_file() else None
    ok = rc == 0 and vals is not None and len(vals) == len(entries) + 1
    result = {"header": rel, "compiler": str(vc6), "cpp": used_cpp, "compile_ok": rc == 0, "compile_log": log[-3000:],
              "structs": [], "assert_checks": [], "parser_mismatches": [], "notes": notes}
    if not ok:
        result["error"] = "compile failed" if rc != 0 else f"could not read the listing ({asm})"
    else:
        table = {}
        for (ref, kind, path), v in zip(entries, vals):
            table.setdefault(ref, {"size": None, "align": None, "off": {}})
            if kind == "off":
                table[ref]["off"][path] = v
            else:
                table[ref][kind] = v
        by_ref = {struct_ref(d): d for d in structs}
        for ref, t in table.items():
            d = by_ref[ref]
            lay = idx.layout(d)
            result["structs"].append({"struct": ref, "file": d.file, "line": d.line, "pack": lay.pack,
                                      "sizeof": t["size"], "align": t["align"], "offsets": t["off"],
                                      "parser_size": lay.size, "parser_exact": lay.exact,
                                      "parser_issues": lay.issues})
            if lay.size != t["size"]:
                result["parser_mismatches"].append(f"{ref}: sizeof parser 0x{lay.size:X} != VC6 0x{t['size']:X}"
                                                   + ("" if lay.exact else f" (parser inexact: {'; '.join(lay.issues[:2])})"))
            if lay.align != t["align"]:
                result["parser_mismatches"].append(f"{ref}: alignment parser {lay.align} != VC6 {t['align']}")
            for m in lay.members:
                if m.bits is not None:
                    continue
                v = t["off"].get(m.path)
                if v is not None and v != m.offset:
                    result["parser_mismatches"].append(f"{ref}.{m.path}: offset parser 0x{m.offset:X} != VC6 0x{v:X}")
        # header asserts
        text = C.mask(hdr.read_text(encoding="utf-8", errors="replace"))
        name_map = {}
        for ref, t in table.items():
            d = by_ref[ref]
            for n in d.names:
                name_map[n] = ref
        for m in ASSERT_SIZE.finditer(text):
            nm = " ".join(m.group(1).split())
            nm = re.sub(r"^(struct|union|class)\s+", "", nm)
            ref = name_map.get(nm)
            want = idx.eval_const(m.group(2), rel)
            if ref is None:
                continue
            got = table[ref]["size"]
            result["assert_checks"].append({"assert": f"sizeof({nm}) == {m.group(2)}", "want": want, "vc6": got,
                                            "status": "OK" if want == got else "MISMATCH" if want is not None else "UNEVALUATED"})
        for m in ASSERT_OFF.finditer(text):
            nm = re.sub(r"^(struct|union|class)\s+", "", " ".join(m.group(1).split()))
            ref = name_map.get(nm)
            if ref is None:
                continue
            want = idx.eval_const(m.group(3), rel)
            got = table[ref]["off"].get(m.group(2))
            result["assert_checks"].append({"assert": f"offsetof({nm}, {m.group(2)}) == {m.group(3)}", "want": want,
                                            "vc6": got,
                                            "status": "OK" if (want == got and got is not None) else
                                            ("MISMATCH" if want is not None and got is not None else "UNEVALUATED")})
    bad_assert = [c for c in result["assert_checks"] if c["status"] == "MISMATCH"]
    result["ok"] = ok and not bad_assert and not result["parser_mismatches"]
    out = Path(a.out) if a.out else scratch
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{stem}.layout_check.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    write_md(out / f"{stem}.layout_check.md", result)
    if not ok:
        print(f"{rel}: {result['error']}\n{log[-1500:]}")
        return 1
    n_off = sum(len(s["offsets"]) for s in result["structs"])
    nok = sum(1 for c in result["assert_checks"] if c["status"] == "OK")
    print(f"{rel}: {len(result['structs'])} structs, {n_off} offsets probed ({'C++' if used_cpp else 'C'}); "
          f"header asserts {nok}/{len(result['assert_checks'])} OK, {len(bad_assert)} mismatch; "
          f"parser vs VC6 mismatches {len(result['parser_mismatches'])}")
    for s in bad_assert[:10]:
        print("  ASSERT MISMATCH", s)
    for s in result["parser_mismatches"][:15]:
        print("  PARSER", s)
    return 0 if result["ok"] else 1


def write_md(path: Path, r: dict):
    L = [f"# layout_check: `{r['header']}`\n", f"compiler `{r['compiler']}`, {'C++' if r['cpp'] else 'C'}; "
         f"compile {'ok' if r['compile_ok'] else 'FAILED'}\n"]
    if r.get("error"):
        L.append(f"**{r['error']}**\n\n```\n{r['compile_log']}\n```\n")
    else:
        L.append("## Structs\n")
        L.append("| struct | pack | sizeof (VC6) | align | parser size | members probed | parser exact |")
        L.append("|---|---|---|---|---|---|---|")
        for s in r["structs"]:
            L.append(f"| {s['struct']} | {s['pack']} | {hexs(s['sizeof'])} | {s['align']} | {hexs(s['parser_size'])} | "
                     f"{len(s['offsets'])} | {'yes' if s['parser_exact'] else 'no'} |")
        L.append("")
        bad = [c for c in r["assert_checks"] if c["status"] != "OK"]
        L.append(f"## Header C_ASSERTs\n\n{len(r['assert_checks'])} checked, {len(bad)} not OK.\n")
        for c in bad:
            L.append(f"- {c['status']}: `{c['assert']}` (header says {c['want']}, VC6 {c['vc6']})")
        L.append("\n## Parser vs VC6\n")
        L.append("\n".join(f"- {x}" for x in r["parser_mismatches"]) or "No differences: the parser's offsets, sizes and alignments equal VC6's.")
        L.append("\n## Offsets (VC6)\n")
        for s in r["structs"]:
            L.append(f"### {s['struct']}  (sizeof {hexs(s['sizeof'])}, align {s['align']})\n")
            L.append(", ".join(f"{k}=0x{v:X}" for k, v in s["offsets"].items()))
            L.append("")
        if r["notes"]:
            L.append("## Notes\n")
            L.append("\n".join(f"- {n}" for n in r["notes"][:50]))
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
