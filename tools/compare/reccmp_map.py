r"""Map our `// FUNCTION: TRILOGY 0x...` annotations to what reccmp (isledecomp/reccmp) expects.

Our marker line is reccmp's own syntax (`// FUNCTION: <target> <address>`, target id `TRILOGY`), but our
convention puts more comment lines between the marker and the definition:

    // FUNCTION: TRILOGY 0x004197a7
    // ORIGINAL FILE: Source/PC Source/EverQuest/EQ_Character.cpp (address range)
    // __thiscall. Bit 0 of the expansion flags ...
    int EQ_Character::ExpansionFlag1_guess(void)

reccmp reads a comment directly after a marker as the function's *name* (its "annotate a comment of the
function name" form, for templates and library code), so 676 of our 733 markers would turn into name lookups
of "ORIGINAL FILE: ..." and fail. Measured 2026-10-04 with reccmp 0.1.7's DecompParser on eq-trilogy src/.

Instead of a second set of comments, reccmp gets a rewritten view of each source, the same number of lines:
the marker lines of a block move down to sit directly above the definition, the comment lines they jumped
over go blank. Line numbers of code are unchanged, so reccmp's line-based match (PDB line info of the
definition) works; with that, all 733 markers parse as line-based FUNCTION markers.

    reccmp_text(text)              -> the rewritten text
    code_files(paths)              -> [reccmp TextFile] (real paths, rewritten text), for reccmp.compare.Compare
    python reccmp_map.py --mirror <dir> [--repo .]
                                   -> <dir>\src\... rewritten copies + reccmp-project.yml / reccmp-user.yml,
                                      for the reccmp CLI tools (reccmp-reccmp, -vtable, -datacmp; PLAN Phase 3)
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "unicorn"))

# Any reccmp-style marker: `// TYPE: TARGET 0x...` (FUNCTION, STUB, GLOBAL, VTABLE, ...).
MARKER = re.compile(r"^\s*//\s*[A-Z_]+\s*:\s*\w+\s+0x[0-9a-fA-F]+")

# Our `// EXTERNAL: TARGET 0x... name` (a declared-only function at a client VA, eqd_unicorn/externs.py) has no
# reccmp counterpart: the reccmp view blanks it.
EXTERNAL = re.compile(r"^\s*//\s*EXTERNAL\s*:")

TARGET_ID = "TRILOGY"


def _is_comment_or_blank(line: str) -> bool:
    s = line.strip()
    return not s or s.startswith("//")


def reccmp_text(text: str) -> str:
    """`text` with every marker block moved directly above its definition (same line count)."""
    lines = ["" if EXTERNAL.match(ln) else ln for ln in text.split("\n")]
    i = 0
    while i < len(lines):
        if not MARKER.match(lines[i]):
            i += 1
            continue
        j = i
        while j < len(lines) and _is_comment_or_blank(lines[j]):
            j += 1
        # lines[i:j]: the markers and the comments/blank lines up to the definition at j
        block = lines[i:j]
        markers = [ln.strip() for ln in block if MARKER.match(ln)]
        new = [""] * (len(block) - len(markers)) + markers
        lines[i:j] = new
        i = j
    return "\n".join(lines)


def code_files(paths, encoding="utf-8"):
    """reccmp TextFiles for `paths`: the real (resolved) path, the rewritten text."""
    from reccmp.formats.textfile import TextFile
    return [TextFile(Path(p).resolve(), reccmp_text(Path(p).read_text(encoding=encoding, errors="replace")))
            for p in paths]


def mirror(repo: Path, out: Path, client="trilogy") -> int:
    """Rewritten copies of repo/src/** under out/src/** plus reccmp-project.yml and reccmp-user.yml (original
    binary from paths.local.ini). reccmp matches PDB source paths to local files by name and path suffix, so a
    PDB built from repo/src/X/Y.cpp finds out/src/X/Y.cpp. reccmp-build.yml (the rebuilt exe + PDB) is left to
    the build that makes them."""
    from eqd_unicorn import Workspace
    repo, out = Path(repo).resolve(), Path(out).resolve()
    n = 0
    for p in sorted((repo / "src").rglob("*")):
        if p.is_file() and p.suffix.lower() in (".c", ".cpp", ".h"):
            dst = out / p.relative_to(repo)
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(reccmp_text(p.read_text(encoding="utf-8", errors="replace")), encoding="utf-8")
            n += 1
    ws = Workspace(repo)
    exe = ws.binary(client)
    sha = hashlib.sha256(exe.read_bytes()).hexdigest() if exe.is_file() else "unknown"
    (out / "reccmp-project.yml").write_text(
        "# Generated by tools/compare/reccmp_map.py --mirror (do not edit; rerun instead).\n"
        "targets:\n"
        f"  {TARGET_ID}:\n"
        f"    filename: {exe.name}\n"
        "    source-root: src\n"
        "    hash:\n"
        f"      sha256: {sha}\n", encoding="utf-8")
    (out / "reccmp-user.yml").write_text(
        "targets:\n"
        f"  {TARGET_ID}:\n"
        f"    path: {exe.as_posix()}\n", encoding="utf-8")
    return n


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=".", help="decomp repo (default: the current directory)")
    ap.add_argument("--client", default="trilogy")
    ap.add_argument("--mirror", required=True, metavar="DIR", help="write the rewritten source tree here")
    args = ap.parse_args(argv)
    n = mirror(Path(args.repo), Path(args.mirror), args.client)
    print(f"reccmp_map: {n} files -> {args.mirror}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
