r"""PROGRESS.md for a decomp repo: per image, functions rewritten, fixture-tested and byte-identical.

    cd eq-trilogy
    ..\.venv\Scripts\python.exe tools\compare\compare.py --client trilogy --match --json ..\build\match\trilogy.json
    (the same for eqmain and eqgfx), then
    ..\.venv\Scripts\python.exe tools\compare\progress.py --compare trilogy=..\build\match\trilogy.json ^
        --compare eqmain=..\build\match\eqmain.json --compare eqgfx=..\build\match\eqgfx.json --out PROGRESS.md

Counts, per image (client id):
  rewritten       distinct addresses with a `// FUNCTION: <TOKEN> 0x...` annotation in the image's sources
  fixture-tested  distinct addresses that a differential fixture (tests/unicorn/<prefix>/**/*.json) runs as its
                  "original"
  compared        functions compare.py --match built and compared (its JSON's results)
  identical       functions whose bytes equal the original's outside relocated fields (compare's bytes_identical)
  identical code  the instructions in those functions, as a share of all compared instructions
  similarity      the instruction-weighted average of compare's ratio (difflib, identical functions count 1.0)
The compare JSON needs the original binaries and VC6, so PROGRESS.md is generated locally and committed; the
numbers are as of the commit it names. --json also writes the counts (and a shields.io endpoint per image).
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
ANN = re.compile(r"^[ \t]*//\s*FUNCTION:\s*([A-Z0-9_]+)\s+0x([0-9A-Fa-f]+)", re.M)
ORIG = re.compile(r'"original"\s*:\s*"0x([0-9A-Fa-f]+)"')


def load_clients():
    spec = importlib.util.spec_from_file_location("eqd_clients_progress", TOOLS / "unicorn" / "eqd_unicorn" / "clients.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def annotated(repo: Path, client) -> set:
    vas = set()
    for p in client.src_dir(repo).rglob("*"):
        if p.suffix.lower() not in (".c", ".cpp") or not p.is_file():
            continue
        rel = p.relative_to(repo / "src").as_posix()
        if client.primary and rel.split("/")[0] in OTHER_PREFIXES:
            continue                                # src/eqmain/, src/eqgfx/ belong to the other images
        for tok, va in ANN.findall(p.read_text(encoding="utf-8", errors="replace")):
            if tok == client.token:
                vas.add(int(va, 16))
    return vas


def tested(repo: Path, client) -> set:
    base = repo / "tests" / "unicorn" / client.prefix if client.prefix else repo / "tests" / "unicorn"
    vas = set()
    for p in base.rglob("*.json"):
        if "negative" in p.parts or p.parent == repo / "tests" / "unicorn":
            continue
        rel = p.relative_to(repo / "tests" / "unicorn").as_posix()
        if client.primary and rel.split("/")[0] in OTHER_PREFIXES:
            continue
        m = ORIG.search(p.read_text(encoding="utf-8", errors="replace"))
        if m:
            vas.add(int(m.group(1), 16))
    return vas


OTHER_PREFIXES: set = set()


def counts(repo: Path, cid: str, compare_json: Path | None, clients) -> dict:
    c = clients.get(cid)
    out = {"client": cid, "binary": Path(c.binary).name if c.binary else cid,
           "rewritten": len(annotated(repo, c)), "tested": len(tested(repo, c))}
    if compare_json:
        d = json.loads(Path(compare_json).read_text(encoding="utf-8"))
        res = d.get("results", [])
        out["compared"] = len(res)
        out["identical"] = sum(1 for r in res if r.get("bytes_identical"))
        out["instructions"] = sum(r.get("orig_count") or 0 for r in res)
        out["identical_instructions"] = sum(r.get("orig_count") or 0 for r in res if r.get("bytes_identical"))
        out["weighted_ratio"] = sum((r.get("orig_count") or 0) * (r.get("ratio") or 0) for r in res)
    return out


def percent(part, whole) -> str:
    return f"{100 * part / whole:.1f}%" if whole else "-"


def row(name, r) -> str:
    if not r.get("compared"):
        return f"| {name} | {r['rewritten']} | {r['tested']} | - | - | - |"
    fns = f"{r['identical']} of {r['compared']} ({percent(r['identical'], r['compared'])})"
    return (f"| {name} | {r['rewritten']} | {r['tested']} | {fns} | "
            f"{percent(r['identical_instructions'], r['instructions'])} | "
            f"{percent(r['weighted_ratio'], r['instructions'])} |")


def render(rows, commit: str) -> str:
    lines = ["# Progress", "",
             f"Generated by `tools/compare/progress.py` at {commit} from the repo's sources and fixtures and",
             "a local `compare.py --match` run against the original binaries (not included; see README.md).", "",
             "| Image | Rewritten | Fixture-tested | Identical functions | Identical code | Similarity |",
             "|---|---:|---:|---:|---:|---:|"]
    lines += [row(f"`{r['binary']}`", r) for r in rows]
    done = [r for r in rows if r.get("compared")]
    if len(done) > 1:
        total = {k: sum(r[k] for r in done) for k in ("rewritten", "tested", "compared", "identical", "instructions",
                                                      "identical_instructions", "weighted_ratio")}
        lines.append(row("**Total**", total))
    lines += ["",
              "- **Rewritten**: functions with a `// FUNCTION:` annotation, i.e. reconstructed source exists.",
              "- **Fixture-tested**: a differential fixture runs the original and the rewrite side by side in an emulator",
              "  (`tests/unicorn/`). This counts fixtures, not the result of a particular run.",
              "- **Identical functions**: VC6 compiles the rewrite to the original's bytes, outside relocated fields.",
              "- **Identical code**: the instructions in those functions as a share of all instructions. Large functions",
              "  count for more, so this is the stricter figure; it is what objdiff calls fully matched code.",
              "- **Similarity**: instruction-weighted `difflib` similarity to the original, the same idea as objdiff's",
              "  fuzzy match but not the same algorithm, so don't compare it across projects.",
              "- The rest behave the same under their fixtures but differ in code generation (register choice, block",
              "  order, ...). Library code (C runtime, zlib, DirectX glue) and exception funclets are not counted.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=".", help="decomp repo (default .)")
    ap.add_argument("--compare", action="append", default=[], metavar="CLIENT=JSON",
                    help="a compare.py --match --json output per image; repeat (order = table order)")
    ap.add_argument("--repo-name", help="the repo's registered name (clients.py; default: its folder name, else eq-trilogy)")
    ap.add_argument("--out", help="write PROGRESS.md here (default: stdout)")
    ap.add_argument("--json", help="also write the counts as JSON (with shields.io endpoint objects)")
    ap.add_argument("--commit", help="what to name as the source version (default: the repo's short HEAD)")
    a = ap.parse_args(argv)
    repo = Path(a.repo).resolve()
    clients = load_clients()
    name = a.repo_name or (repo.name if clients.of_repo(repo.name) else "eq-trilogy")   # a worktree has another name
    OTHER_PREFIXES.update(c.prefix for c in clients.of_repo(name) if c.prefix)
    pairs = [x.split("=", 1) for x in a.compare]
    if not pairs:
        pairs = [[c.id, None] for c in clients.of_repo(name)]
    rows = [counts(repo, cid, js, clients) for cid, js in pairs]
    try:
        commit = a.commit or "commit `%s`" % subprocess.run(["git", "-C", str(repo), "rev-parse", "--short=8", "HEAD"],
                                                           capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"
    text = render(rows, commit)
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    else:
        print(text)
    if a.json:
        badges = {r["client"]: {"schemaVersion": 1, "label": r["binary"],
                                "message": f"{r['identical']}/{r['compared']} identical" if r.get("compared") else
                                f"{r['tested']} tested", "color": "blue"} for r in rows}
        Path(a.json).write_text(json.dumps({"commit": commit, "rows": rows, "shields": badges}, indent=1),
                                encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
